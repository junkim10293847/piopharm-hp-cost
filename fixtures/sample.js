// 테스트용 가상 기초 파일 (실제 회사 데이터 아님)
// 계산 결과를 손으로 검산할 수 있도록 작은 숫자로 구성
const XLSX = require('xlsx');

function sheet(aoa) { return XLSX.utils.aoa_to_sheet(aoa); }
function at(row, col) { return XLSX.utils.encode_cell({ r: row, c: col }); }

function buildFixture() {
  const wb = XLSX.utils.book_new();

  // ---- 당월 생산 (기존 수식 시트 형식: 제공자료 칸 + 전월 생산 구간) ----
  const hdr = [];
  hdr[1] = 'No.'; hdr[2] = '제품코드\n(제공자료)'; hdr[3] = '제품코드'; hdr[5] = '로트번호\n(제공자료)'; hdr[6] = '로트번호\n(확인)';
  hdr[7] = '제품명'; hdr[8] = '고객사'; hdr[9] = '평택비율'; hdr[10] = '평택비율'; hdr[12] = '규격'; hdr[13] = '완료수량'; hdr[14] = '완료단가';
  hdr[20] = '단가'; hdr[35] = '생산중량(kg)';
  const lot = (code, lotNo, name, line, spec, qty, price) => {
    const r = []; r[1] = 1; r[2] = code; r[3] = code; r[5] = lotNo; r[6] = lotNo; r[7] = name; r[8] = '홍길동상사';
    r[9] = line; r[10] = line === '평택' ? 1 : 0.8; r[12] = spec; r[13] = qty; r[14] = price; return r;
  };
  const prev = lot('1AA0000003', 'T004', '테스트 마그네슘액', '평택', 14, 500, 2000);
  prev[20] = 1950; prev[35] = 140; prev[49] = 0.5; // AX열 = 보정계수
  const main = sheet([
    [null, '제공자료'],
    hdr,
    lot('1AA0000001', 'T001', '테스트 오메가', '평택', 30, 1000, 1000),
    lot('1AA0000001', 'T002', '테스트 오메가', '평택', 30, 3000, 1000),
    lot('1AA0000002', 'T003', '테스트 비타민', '화성포장', 60, 2000, 500),
    [],
    [null, '전월 생산'],
    hdr,
    prev,
  ]);
  main[at(8, 20)].f = 'IFERROR(VLOOKUP(G9,발주!B:AE,13,FALSE),"확인불가")*1300';
  main[at(8, 35)].f = "VLOOKUP(G9,'자재투입현황'!A:K,9,FALSE)*AX9";
  XLSX.utils.book_append_sheet(wb, main, '당월 생산');

  // ---- 발주 현황 ----
  XLSX.utils.book_append_sheet(wb, sheet([
    [null, '2026년 납기대장'],
    ['매출 월', 'LOT', '제품코드', '구분', '수주수량 ', '수주단가'],
    [9, 'T001', '1AA0000001', '건식', 1000, 1000],
    [9, 'T002', '1AA0000001', '건식', 3000, 1000],
    [9, 'T003', '1AA0000002', '건식', 2000, 500],
    [9, 'T004', '1AA0000003', '건식', 500, 1.5],
    [8, 'T001', '1AA0000001', '건식', 999, 9],        // 다른 달 → 제외되어야 함
    ['매출 월', 'LOT', '제품코드', '구분', '수주수량', '수주단가'], // 반복 머리글 → 제외
  ]), '2026년 발주 현황');

  // ---- 작업지시현황 (같은 로트에 반제품 행이 섞여 있음) ----
  XLSX.utils.book_append_sheet(wb, sheet([
    ['No', '제품로트번호', '지시제품', '제품명', '규격'],
    [1, 'T001', '3AA0000001', '테스트 오메가(반)', '1,000mg/연질캡슐'],
    [2, 'T001', '1AA0000001', '테스트 오메가', '1,000mg x 30연질캡슐/set'],
    [3, 'T002', '1AA0000001', '테스트 오메가', '1,000mg x 30연질캡슐/set'],
    [4, 'T003', '1AA0000002', '테스트 비타민', '500mg x 60정 x 2ea/set'],
    [5, 'T004', '1AA0000003', '테스트 마그네슘액', '20g x 14포/set'],
  ]), '작업지시현황(당월)');

  // ---- 9월 출하대장 ----
  XLSX.utils.book_append_sheet(wb, sheet([
    ['No', '로트번호', '품목코드', '제품명', '매출업체', '출하량', '중량', '공급가액'],
    [1, 'T001', '1AA0000001', '테스트 오메가', '홍길동상사', 1000, 30, 1000000],
    [2, 'T002', '1AA0000001', '테스트 오메가', '홍길동상사', 3000, 90, 3000000],
    [3, 'T003', '1AA0000002', '테스트 비타민', '홍길동상사', 2000, 60, 1000000],
    [4, 'T004', '1AA0000003', '테스트 마그네슘액', '홍길동상사', 500, 140, 975000],
    [5, 'H001', '1BB0000001', '테스트 화성정', '홍길동유통', 1000, 100, 5000000],
    [6, 'H002', '1BB0000001', '테스트 화성정', '홍길동유통', 500, 50, 2500000],
    [7, 'X001', '4C00009999', '원료 판매', '홍길동유통', 1, 0, 300000],
  ]), '9월 출하대장');

  // ---- 제품 단가 대장 (9월, 8월) ----
  const ledHdr = ['No', '작업일자', '품목코드', '생산중량', '자재코드', '상세금액'];
  XLSX.utils.book_append_sheet(wb, sheet([
    ledHdr,
    [1, '2026.09', '1AA0000001', 120, '3AA0000001', 600000],
    [2, '2026.09', '1AA0000001', 120, '4C00000149', 100000],
    [3, '2026.09', '1AA0000001', 120, '6CE0000001', 300000],
    [4, '2026.09', '3AA0000001', 125, '4C00000001', 500000], // 반제품 행 → 제외
    [5, '2026.09', '1AA0000002', 60, '3AA0000002', 400000],
    [6, '2026.09', '1AA0000002', 60, '6CE0000002', 100000],
    [7, '2026.09', '1BB0000001', 200, '3BB0000001', 1500000],
    [8, '2026.09', '1BB0000001', 200, '6CE0000003', 500000],
  ]), '9월 제품 단가 대장');
  XLSX.utils.book_append_sheet(wb, sheet([
    ledHdr,
    [1, '2026.08', '1AA0000003', 280, '3AA0000003', 2000000],
    [2, '2026.08', '1AA0000003', 280, '6CE0000004', 800000],
    [3, '2026.08', '1AA0000001', 50, '3AA0000001', 999999], // T001은 9월 제조 → 쓰면 안 됨
  ]), '8월 제품 단가 대장');

  // ---- 자재투입현황 (같은 투입번호 중복 행 포함) ----
  XLSX.utils.book_append_sheet(wb, sheet([
    ['No', '제조일자', '투입번호', '생산중량', '투입중량', '반제품/자재로트번호'],
    [1, '2026.09.05', 'I-1', 30, 31, 'T001'],
    [2, '2026.09.05', 'I-1', 30, 31, 'T001'],
    [3, '2026.09.06', 'I-2', 90, 92, 'T002'],
    [4, '2026.09.07', 'I-3', 60, 62, 'T003'],
    [5, '2026.08.20', 'I-4', 280, 290, 'T004'],
  ]), '자재투입현황(6-9)');

  return wb;
}

// 파일로 저장했다가 다시 읽은 것과 같은 상태로 돌려줌
function fixtureWorkbook() {
  const buf = XLSX.write(buildFixture(), { type: 'buffer', bookType: 'xlsx' });
  return XLSX.read(buf, { type: 'buffer', cellFormula: true, cellDates: true });
}

module.exports = { buildFixture, fixtureWorkbook };

if (require.main === module) {
  const out = process.argv[2] || 'sample/가상_기초파일.xlsx';
  require('fs').mkdirSync(require('path').dirname(out), { recursive: true });
  XLSX.writeFile(buildFixture(), out);
  console.log('가상 기초 파일 생성:', out);
}
